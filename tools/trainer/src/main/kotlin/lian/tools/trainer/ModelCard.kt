package lian.tools.trainer

/** Generates docs/ml-model-card.md from the trained models, so the documentation can't drift from what ships. */
object ModelCard {
    fun render(props: Props, results: List<Train.Result>): String = buildString {
        appendLine("# LIAN on-device models: model card")
        appendLine()
        appendLine("Generated by `./gradlew :tools:trainer:trainModels` — do not edit by hand. Corpus date: ${props["corpus.date"]}.")
        appendLine()
        appendLine("## What they are")
        appendLine()
        appendLine("Two small logistic-regression classifiers over hashed binary features (`LinearModel`, format LNM1).")
        appendLine("They run entirely on the phone, in pure Kotlin, with no ML runtime, no native code and no network.")
        appendLine("Weights are 8-bit integers, so the raw score is an exact integer sum: identical on every device.")
        appendLine("Each file is listed in the intel SHA-256 manifest and refused at runtime if altered.")
        appendLine()
        appendLine("| Model | File | Input | Featurizer | Size |")
        appendLine("|---|---|---|---|---|")
        for (r in results) {
            val input = if (r.spec.name == "message") "the text of a message (English)" else "the registrable name of a link's domain"
            appendLine("| ${r.spec.name} | `${r.spec.file}` | $input | `${r.model.featurizerId}` (2^${r.model.bits} buckets) | ${r.model.encode().size / 1024} KB |")
        }
        appendLine()
        appendLine("## How they are used")
        appendLine()
        appendLine("- **They add evidence; they never decide alone.** A model hit is one finding (`msg.ml.pattern`, `link.ml.domain`) in the")
        appendLine("  same noisy-OR score as the hand-written rules. On its own a model can raise a result to *Be careful*; reaching")
        appendLine("  *Likely a scam* or *Dangerous* needs a deterministic rule as well.")
        appendLine("- **Every hit is explained.** The finding lists the words, domain parts or signals that contributed most.")
        appendLine("- **Official brand domains are never scored** by the domain model.")
        appendLine()
        appendLine("## Data")
        appendLine()
        appendLine("| Source | Use | Licence | Pinned by |")
        appendLine("|---|---|---|---|")
        appendLine("| UCI SMS Spam Collection (Almeida et al., 2011) | message: ham / spam | ${props.opt("uci.license")} | SHA-256 `${props.opt("uci.sha256").take(16)}…` |")
        appendLine("| Mishra & Soni, SMS Phishing Dataset (Mendeley Data, 2022) | message: ham / spam / smishing | ${props.opt("mishra.license")} | SHA-256 `${props.opt("mishra.sha256").take(16)}…` |")
        appendLine("| Hand-written examples (`tools/trainer/corpus/authored-messages.tsv`) | message: recent scam formats and genuine OTP/delivery texts; **training only** | project licence | in repository |")
        appendLine("| Phishing.Database, active domains (pinned commit) | domain: phishing | ${props.opt("phishdb.license")} | SHA-256 `${props.opt("phishdb.sha256").take(16)}…` |")
        appendLine("| Majestic Million (${props["corpus.date"]}) | domain: ordinary | ${props.opt("majestic.license")} | SHA-256 `${props.opt("majestic.sha256").take(16)}…` |")
        appendLine()
        appendLine("Messages labelled spam or smishing are positives. Exact duplicates across the two datasets are merged and texts")
        appendLine("labelled both ways are dropped. Domains are reduced to their registrable label with the Public Suffix List;")
        appendLine("phishing hosts on popular (Majestic-listed) domains are skipped as compromised rather than deceptive.")
        appendLine("Samples are split 80/10/10 (train/validation/test) by a hash of the normalised text.")
        appendLine()
        appendLine("## Results on the held-out test split")
        appendLine()
        appendLine("| Model | Test samples | AUC | High: precision / recall / false-positive rate | Medium: precision / recall / FPR |")
        appendLine("|---|---|---|---|---|")
        for (r in results) {
            val m = r.model.metadata
            appendLine(
                "| ${r.spec.name} | ${m["test.samples"]} | ${m["test.auc"]} | ${m["test.high.precision"]} / ${m["test.high.recall"]} / ${m["test.high.fpr"]} | " +
                    "${m["test.medium.precision"]} / ${m["test.medium.recall"]} / — |",
            )
        }
        appendLine()
        appendLine("Thresholds were chosen on the validation split: *high* at ≥ ${pct(results, "message", true)} (messages) and")
        appendLine("≥ ${pct(results, "domain", true)} (domains) validation precision, *medium* at ≥ 90 %.")
        appendLine("Precision depends on how common scams are in what is checked; these figures are at the corpus ratio.")
        appendLine()
        appendLine("## Limitations")
        appendLine()
        appendLine("- **English only.** Messages in other languages get no model score (rules still apply).")
        appendLine("- **Dated public data.** The SMS datasets are from 2011–2022; recent formats are covered only by a small set of")
        appendLine("  hand-written examples. Expect lower recall on new scam styles.")
        appendLine("- **Names, not intent.** The domain model judges how a name looks. A phishing page on a hacked, ordinary-looking")
        appendLine("  site scores low; a legitimate site with a random-looking name may score high (hence *Be careful*, not more).")
        appendLine("- **No learning on the phone.** Models change only through a signed app update; nothing about what you check is")
        appendLine("  kept or used for training.")
        appendLine()
        appendLine("## Training procedure")
        appendLine()
        appendLine("AdaGrad logistic regression, 6 epochs, learning rate 0.2, balanced class weights, L2 chosen from {1e-6, 1e-5, 1e-4}")
        appendLine("on validation log-loss; deterministic SplitMix64 shuffle; 8-bit quantisation with the scale chosen on validation;")
        appendLine("the encoded file is re-decoded and re-scored against the trainer before it is written.")
        for (r in results) {
            appendLine()
            appendLine("- `${r.spec.file}`: L2 ${r.model.metadata["l2"]}, ${r.model.metadata["train.samples"]} training samples, " +
                "thresholds (logit) medium ${Train.fmt(r.model.mediumLogit)}, high ${Train.fmt(r.model.highLogit)}.")
        }
    }

    private fun pct(results: List<Train.Result>, name: String, high: Boolean): String {
        val spec = results.first { it.spec.name == name }.spec
        return "${((if (high) spec.highPrecision else spec.mediumPrecision) * 100).toInt()} %"
    }
}
